// A user entry in the transcript is not always something Brendon typed:
// Claude Code also writes slash commands, their output, "!" shell lines,
// interruptions and background-task notices as user messages, wrapped in its
// own tags. This sorts them so the Chat view draws each as what it is.

export type UserPart =
  | { kind: 'prompt'; text: string }
  | { kind: 'command'; text: string }
  | { kind: 'output'; text: string; isError: boolean }
  | { kind: 'interrupt'; text: string }
  | { kind: 'notice'; text: string }
  | { kind: 'hidden' }

// eslint-disable-next-line no-control-regex -- escape sequences are what this strips
const ANSI = /\x1b\[[0-9;?]*[ -/]*[@-~]|\x1b\][^\x07\x1b]*(?:\x07|\x1b\\)/g
export const stripAnsi = (s: string) => s.replace(ANSI, '')

const tag = (s: string, name: string): string | null => {
  const m = new RegExp(`<${name}>([\\s\\S]*?)</${name}>`).exec(s)
  return m ? m[1] : null
}

const DROP = /<(system-reminder|user-prompt-submit-hook|command-message)>[\s\S]*?<\/\1>/g

export function userPart(raw: string): UserPart {
  const s = raw.replace(DROP, '').trim()
  if (!s) return { kind: 'hidden' }
  if (/^Caveat: The messages below were generated by the user while running local commands/.test(s)) return { kind: 'hidden' }
  if (/^\[Request interrupted by user/.test(s)) return { kind: 'interrupt', text: /for tool use/.test(s) ? 'Interrupted during a tool call' : 'Interrupted' }

  const cmd = tag(s, 'command-name')
  if (cmd !== null) {
    const args = (tag(s, 'command-args') ?? '').trim()
    return { kind: 'command', text: `${cmd.trim()}${args ? ` ${args}` : ''}` }
  }
  const bash = tag(s, 'bash-input')
  if (bash !== null) return { kind: 'command', text: `! ${bash.trim()}` }
  // the server already unwrapped these: "/model opus", "! git status"
  if (!s.includes('\n') && s.length <= 300 && (/^\/[\w:.-]+(?:\s|$)/.test(s) || /^! \S/.test(s))) return { kind: 'command', text: s }

  const out = tag(s, 'local-command-stdout') ?? tag(s, 'bash-stdout')
  const err = tag(s, 'local-command-stderr') ?? tag(s, 'bash-stderr')
  if (out !== null || err !== null) {
    const text = stripAnsi([out ?? '', err ?? ''].filter((x) => x.trim()).join('\n')).trim()
    return text ? { kind: 'output', text, isError: !out?.trim() && !!err?.trim() } : { kind: 'hidden' }
  }

  if (/^<task-notification>/.test(s)) {
    const body = tag(s, 'task-notification') ?? s
    const summary = tag(body, 'summary') ?? tag(body, 'status') ?? body.replace(/<[^>]+>/g, ' ')
    return { kind: 'notice', text: summary.replace(/\s+/g, ' ').trim() || 'Background task update' }
  }
  return { kind: 'prompt', text: s }
}
